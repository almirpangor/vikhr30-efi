def xf(x, y, rot):
    """Локальная точка → повёрнутая (соглашение KiCad: +угол — против часовой на экране, Y вниз)."""
    a = math.radians(rot); c, s = round(math.cos(a), 9), round(math.sin(a), 9)
    return (x * c + y * s, -x * s + y * c)
