"""Посадочные места. Локальные координаты: мм, ось Y вниз (как в KiCad), поворот — против часовой на экране.
Каждое место: pads [(name, x, y, shape, w, h, drill, layers)], body (контур на сборочном/шелке), court (x0,y0,x1,y1), h (высота).
shape: 'c' круг (w — диаметр), 'r' прямоугольник, 'o' овал; layers: 'T' (SMD сверху) или 'TB' (сквозное)."""
import math

def P(name, x, y, shape, w, h=None, drill=0.0, layers=None):
    return dict(name=str(name), x=x, y=y, shape=shape, w=w, h=h if h is not None else w, drill=drill, layers=layers or ('TB' if drill else 'T'))

def rect(x0, y0, x1, y1):
    return [(x0, y0, x1, y0), (x1, y0, x1, y1), (x1, y1, x0, y1), (x0, y1, x0, y0)]

def circle(cx, cy, r, n=24):
    pts = [(cx + r * math.cos(2 * math.pi * i / n), cy + r * math.sin(2 * math.pi * i / n)) for i in range(n + 1)]
    return [(pts[i][0], pts[i][1], pts[i + 1][0], pts[i + 1][1]) for i in range(n)]

