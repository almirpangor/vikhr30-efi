GLYPH = {k: [[tuple(float(v) for v in pt.split(',')) for pt in pl.split()] for pl in s.split(';') if pl.strip()] for k, s in RAW.items()}
ADV = 5.4   # шаг символа в клетках

def text_width(s, h): return (len(s) * ADV - (ADV - 4)) * h / 6 if s else 0.0

def strokes(s, x, y, h, rot=0, anchor='c', mirror=False):
    """Отрезки текста. (x, y) — точка привязки (по вертикали — середина), rot — градусы против часовой на экране (Y вниз)."""
    s = s.upper(); k = h / 6; wtot = text_width(s, h)
    ox = {'c': -wtot / 2, 'l': 0.0, 'r': -wtot}[anchor]
    a = math.radians(rot); ca, sa = math.cos(a), math.sin(a)
    out = []
    for i, ch in enumerate(s):
        g = GLYPH.get(ch)
        if g is None: raise KeyError(f'нет символа «{ch}» в шрифте')
        for pl in g:
            pts = []
            for (gx, gy) in pl:
                lx = ox + (i * ADV + gx) * k; ly = -(gy - 3) * k
                if mirror: lx = -lx
                pts.append((x + lx * ca + ly * sa, y - lx * sa + ly * ca))
            out += [(pts[j][0], pts[j][1], pts[j + 1][0], pts[j + 1][1]) for j in range(len(pts) - 1)]
    return out

def bbox(s, x, y, h, rot=0, anchor='c'):
    w = text_width(s, h); ox = {'c': -w / 2, 'l': 0.0, 'r': -w}[anchor]
    a = math.radians(rot); ca, sa = math.cos(a), math.sin(a)
    cs = [(ox, -h / 2), (ox + w, -h / 2), (ox + w, h / 2), (ox, h / 2)]
    xs = [x + lx * ca + ly * sa for lx, ly in cs]; ys = [y - lx * sa + ly * ca for lx, ly in cs]
    return (min(xs), min(ys), max(xs), max(ys))
