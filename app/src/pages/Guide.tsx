const STATUS: Record<string, string> = { disconnected: 'не подключено', opening: 'открытие порта', waiting: 'ожидание ответа', online: 'ECU отвечает', lost: 'ECU не отвечает' };

export default function GuidePage() {
  const [sel, setSel] = useState(() => { const i = load('guide.step', 0); return i >= 0 && i < STEPS.length ? i : 0; });
  const [done, setDone] = useState<string[]>(() => { const d = load<string[]>('guide.done', []); return Array.isArray(d) ? d : []; });
  const t = useApp((s) => s.telemetry);
  const live = useApp((s) => s.live) && !!t;
  const status = useApp((s) => s.status);
  const step = STEPS[sel];
  const isDone = done.includes(step.id);
  const pick = (i: number) => { setSel(i); save('guide.step', i); };
  const toggle = () => { const next = isDone ? done.filter((d) => d !== step.id) : [...done, step.id]; setDone(next); save('guide.done', next); };
  const count = STEPS.filter((s) => done.includes(s.id)).length;

  return (
    <div className="page">
      <PageHead title="Настройка по шагам" sub="Порядок первого запуска. Идите сверху вниз и не переходите дальше, пока не выполнен критерий шага." />
      <div className="gd-wrap">
        <div className="card gd-list" role="tablist" aria-label="Шаги настройки" aria-orientation="vertical">
          <div className="gd-progress">Выполнено шагов: {count} из {STEPS.length}</div>
          {STEPS.map((s, i) => {
            const d = done.includes(s.id);
            return (
              <button key={s.id} role="tab" aria-selected={i === sel} className={'gd-step' + (i === sel ? ' active' : '') + (d ? ' done' : '')} onClick={() => pick(i)}>
                <span className="gd-num" aria-hidden="true">{d ? '✓' : i}</span>
                <span>{s.title}{d && <span className="faint" style={{ fontSize: 0 }}> (выполнено)</span>}</span>
              </button>
            );
          })}
        </div>

        <div className="card gd-body" role="tabpanel">
          <div className="row"><h2>Шаг {sel}. {step.title}</h2>{isDone && <span className="tag ok">выполнено</span>}</div>
          <div><h3>Цель</h3><p>{step.goal}</p></div>
          <div><h3>Что сделать</h3><ol>{step.todo.map((x) => <li key={x}>{x}</li>)}</ol></div>
          <div>
            <h3>{step.tune ? 'Что менять' : 'Куда смотреть'}</h3>
            {step.tune && <p style={{ marginBottom: 8 }}>{step.tune}</p>}
            <div className="row">{step.links.map(([page, label]) => <button key={page} className="btn sm" onClick={() => setPage(page)}>{label}</button>)}</div>
          </div>
          <div>
            <h3>Показатели сейчас</h3>
            <div className="gd-live">
              {step.watch.map((k) => {
                if (k === 'link') return <div key={k}><span>Связь</span><b className={status === 'online' ? 'ok' : status === 'lost' ? 'danger' : 'nodata'}>{STATUS[status] ?? status}</b></div>;
                const [label, get] = LIVE[k];
                return <div key={k}><span>{label}</span><b className={live ? '' : 'nodata'}>{live && t ? get(t) : DASH}</b></div>;
              })}
            </div>
            {!live && <p className="muted" style={{ fontSize: 12.5, marginTop: 6 }}>Нет связи с ECU — значения появятся после подключения.</p>}
          </div>
          {step.warn && <div className="banner warn">{step.warn}</div>}
          <div className="banner"><div><b>Шаг выполнен, когда:</b> {step.done}</div></div>
          <div className="gd-done">
            <label><input type="checkbox" checked={isDone} onChange={toggle} />Шаг выполнен</label>
            <span style={{ flex: 1 }} />
            <button className="btn sm" disabled={sel === 0} onClick={() => pick(sel - 1)}>← Назад</button>
            <button className="btn sm" disabled={sel === STEPS.length - 1} onClick={() => pick(sel + 1)}>Дальше →</button>
          </div>
        </div>
      </div>
      <div className="banner danger">Допустимые диапазоны полей не гарантируют безопасность для конкретного мотора. Настройка под нагрузкой — только на стенде, с широкополосной лямбдой, контролем температуры и аппаратным выключателем STOP.</div>
    </div>
  );
}
